GRAPH_EXTRACTION_SYSTEM=(
 'Extract factual knowledge graph entities and relations from this EXACT chunk only. '
 'Return JSON {"entities":[{"name":"...","type":"..."}],"relations":[{"source":"...","relation":"...","target":"..."}]}. '
 'Entities must be short exact substrings present in the source chunk, not inferred. '
 'Relations must be directly supported by source text. No inferred facts. Max 12 entities and 14 relations. '
 'If no factual entities return empty arrays. Do not explain.'
)

def tokens(s):return [x for x in re.findall(r'[^\W_]+',s.casefold(),re.UNICODE) if x not in STOP and len(x)>1]
def now():return datetime.datetime.now(datetime.UTC).isoformat()
def load_jsonl_fromzip(z,p):return [json.loads(x) for x in z.read(PREFIX+p).decode().splitlines() if x.strip()]
def save_jsonl(p,items):
 with open(p,'w',encoding='utf8') as f:
  f.writelines(json.dumps(v,ensure_ascii=False)+'\n' for v in items)
def ollama(host,model,messages,timeout=180,format='json'):
 body=json.dumps({'model':model,'messages':messages,'stream':False,'format':format,'options':{'temperature':0,'num_ctx':4096}}).encode()
 req=urllib.request.Request(host.rstrip('/')+'/api/chat',data=body,headers={'Content-Type':'application/json'},method='POST')
 with urllib.request.urlopen(req,timeout=timeout) as r:result=json.load(r)
 content=result.get('message',{}).get('content','')
 try:return json.loads(content),result
 except json.JSONDecodeError:
  match=re.search(r'\{.*\}',content,re.DOTALL)
  if match:return json.loads(match.group()),result
  raise ValueError('Model response is not valid JSON')

def extract_graph_chunk(host,model,excerpt):
 v,_=ollama(host,model,[{'role':'system','content':GRAPH_EXTRACTION_SYSTEM},{'role':'user','content':excerpt}],format=GRAPH_EXTRACTION_SCHEMA)
 if not isinstance(v,dict):
  raise ValueError('Graph extraction response must be an object')  # noqa: TRY004
 raw_entities=v.get('entities',[])
 raw_relations=v.get('relations',[])
 if not isinstance(raw_entities,list) or not isinstance(raw_relations,list):
  raise ValueError('Graph extraction entities and relations must be lists')  # noqa: TRY004
 if len(raw_entities)>12:
  raise ValueError('Graph extraction entities exceed 12 objects')
 if len(raw_relations)>14:
  raise ValueError('Graph extraction relations exceed 14 objects')
 if any(not isinstance(e,dict) for e in raw_entities):
  raise ValueError('Graph extraction entities contain no valid objects')
 if any(not isinstance(e,dict) for e in raw_relations):
  raise ValueError('Graph extraction relations contain no valid objects')
 ents=[];allowed=set()
 for e in raw_entities:
  if set(e)!={'name','type'} or not isinstance(e.get('name'),str) or not isinstance(e.get('type'),str):
   raise ValueError('Graph extraction entity objects require string name and type fields')
  name=e['name'].strip();kind=e['type'].strip()
  if not 2<=len(name)<115 or not 1<=len(kind)<=50:
   raise ValueError('Graph extraction entity fields violate schema limits')
  if name.casefold() in excerpt.casefold():
   ents.append({'name':name,'type':kind});allowed.add(name.casefold())
 relations=[]
 for e in raw_relations:
  if set(e)!={'source','relation','target'} or not all(isinstance(e.get(k),str) for k in ('source','relation','target')):
   raise ValueError('Graph extraction relation objects require string source, relation, and target fields')
  s=e['source'].strip();t=e['target'].strip();rel=e['relation'].strip()
  if len(s)<2 or len(t)<2 or not 1<=len(rel)<=90:
   raise ValueError('Graph extraction relation fields violate schema limits')
  if s.casefold() in allowed and t.casefold() in allowed and s.casefold()!=t.casefold():
   relations.append({'source':s,'relation':rel,'target':t})
 return ents,relations

def get_bundle(zip_path):
 z=zipfile.ZipFile(zip_path)
 assert 'chunks.jsonl' in [n[len(PREFIX):] for n in z.namelist()], 'Unexpected ZIP layout'
 return z, load_jsonl_fromzip(z,'chunks.jsonl'),load_jsonl_fromzip(z,'questions_with_chunk_mapping.jsonl'),load_jsonl_fromzip(z,'search_results_silver.jsonl')

def select_for_graph(chunks,search,questions,cap):
 # Baseline retrieval union: fixed candidates shared across methods, in decreasing rank relevance.
 byid={c['chunk_id']:c for c in chunks}; score=collections.defaultdict(float)
 for r in search:
  for rank,cid in enumerate(r['ranked_chunk_ids'][:10],1):
   if cid in byid:score[cid]+=1/(20+rank)
 # Include BM25- and baseline-retrieved content before unrelated portions.
 order=sorted(score,key=lambda x:(-score[x],x))
 # Preserve a small breadth sample of each source even if source isn't retrieved.
 for c in chunks:
  if c['source_id']!='3M_2022_10K.md' and c['chunk_id'] not in score:order.append(c['chunk_id'])
 for c in chunks:
  if c['chunk_id'] not in score and c['chunk_id'] not in order:order.append(c['chunk_id'])
 return order[:cap],len(score)

def build_graph(ids,byid,out,host,model,redo=False):
 cache=out/'graph_edges.jsonl'; status=out/'graph_progress.json'
 if redo and cache.exists(): cache.unlink()
 rows=[]
 if cache.exists() and not redo:
  rows=[json.loads(s) for s in cache.read_text().splitlines() if s.strip()]
 done={r['chunk_id'] for r in rows}
 with cache.open('a',encoding='utf8') as f:
  for pos,cid in enumerate(ids,1):
   if cid in done:continue
   c=byid[cid]; original=c.get('text',''); excerpt=original[:4800]
   item={'chunk_id':cid,'source_id':c['source_id'],'extraction_truncated':len(original)>len(excerpt),'entities':[],'relations':[],'error':None,'elapsed_s':None}
   started=time.monotonic()
   for attempt in range(2):
    try:
     ents,relations=extract_graph_chunk(host,model,excerpt)
     item['entities']=ents;item['relations']=relations;item['error']=None;break
    except Exception as exc:  # noqa: BLE001
     item['error']=type(exc).__name__+': '+str(exc)[:170]
     if attempt==0:time.sleep(0.3)
   item['elapsed_s']=round(time.monotonic()-started,2)
   f.write(json.dumps(item,ensure_ascii=False)+'\n');f.flush();rows.append(item)
   status.write_text(json.dumps({'completed':len(rows),'planned':len(ids),'last_chunk':cid,'updated':now()},indent=2),encoding='utf8')
   if pos%10==0 or pos==len(ids):print(f'GRAPH {len(rows)}/{len(ids)} last={cid[:22]}',flush=True)
 return rows

def construct_index(rows):
 entity_chunks=collections.defaultdict(set);adj=collections.defaultdict(set);relations=[]
 for x in rows:
  cid=x['chunk_id']
  for e in x['entities']:entity_chunks[e['name'].casefold()].add(cid)
  for e in x['relations']:
   a=e['source'].casefold();b=e['target'].casefold()
   adj[a].add(b);adj[b].add(a);relations.append({'source':e['source'],'relation':e['relation'],'target':e['target'],'chunk_id':cid,'source_id':x['source_id']})
 return entity_chunks,adj,relations

def graph_search(question,baselines,entity_chunks,adj,byid,graph_set,top_k=10):
 # Valid graph traversal: start at question-mentioned entities and the baseline's top retrieved chunks.
 query=question['question'].casefold(); qt=set(tokens(query)); seeds={}; seed_terms=[]
 for name in entity_chunks:
  if len(name)>=3 and (name in query or (len(tokens(name))>0 and set(tokens(name))<=qt)):
   seed_terms.append(name)
 for cid in baselines.get('V1',[])[:10]+baselines.get('H1',[])[:10]:
  if cid in byid:seeds[cid]=seeds.get(cid,0)+1
 start=set(seed_terms)
 for cid in list(seeds):
  for ent,cs in entity_chunks.items():
   if cid in cs:start.add(ent)
 frontier=set(start);visited=set(start)
 hop_entities={0:set(start)}
 for depth in (1,2):
  nxt=set().union(*(adj.get(e,set()) for e in frontier)) -visited if frontier else set()
  hop_entities[depth]=nxt;visited.update(nxt);frontier=nxt
 candidate=collections.defaultdict(float);why=collections.defaultdict(list)
 for method in ('V1','H1'):
  for rank,cid in enumerate(baselines.get(method,[])[:10],1):
   candidate[cid]+=1/(60+rank)
   why[cid].append({'kind':'baseline','method':method,'rank':rank})
 for depth,terms in hop_entities.items():
  for entity in terms:
   for cid in entity_chunks.get(entity,set()):
    boost=(1.0 if depth==0 else .45 if depth==1 else .18) / 60
    candidate[cid]+=boost
    if len(why[cid])<12:why[cid].append({'kind':'graph','entity':entity,'hop':depth})
 ranking=sorted(candidate,key=lambda cid:(-candidate[cid],cid))[:top_k]
 return [{'chunk_id':cid,'score':round(candidate[cid],7),'trace':why[cid]} for cid in ranking],{'seed_entities':sorted(seed_terms),'graph_start_nodes':len(start),'nodes_hop1':len(hop_entities[1]),'nodes_hop2':len(hop_entities[2]),'candidate_chunks':len(candidate)}

def context_for(ranked,byid,max_chars=12000):
 items=[];total=0
 for idx,item in enumerate(ranked[:10],1):
  c=byid[item['chunk_id']];chunk=c['text'];limit=max(0,max_chars-total)
  if limit<70:break
  text=chunk[:min(limit,2200)]; total+=len(text)
  items.append({'rank':idx,'chunk_id':item['chunk_id'],'source_id':c['source_id'],'source_version':c.get('version'), 'element_ids':c.get('element_ids',[]), 'location_statuses':c.get('location_statuses',[]),'chunk_text_full':chunk,'reference_text_sent':text,'reference_was_truncated':len(chunk)>len(text),'ranking_score':item.get('score'),'retrieval_path':item.get('trace',[])})
 prepared='\n\n'.join(f"[{i['rank']}] CHUNK={i['chunk_id']} SOURCE={i['source_id']} ELEMENTS={','.join(i['element_ids'][:4])}\n{i['reference_text_sent']}" for i in items)
 return items,prepared

def answer(q,ctx,host,model):
 system=('Answer the question using ONLY the provided reference material, in the same language as the question. '
 'Do not use outside knowledge. If insufficient, say that the provided references do not support an answer. '
 'Cite supporting CHUNK ids in "citations". Return JSON {"answer":"...","citations":["sha256:..."],"abstained":true/false}. '
 'Keep answers concise; never invent sources.')
 user=f'QUESTION: {q}\n\nREFERENCES:\n{ctx}'
 started=time.monotonic()
 try:
  v,raw=ollama(host,model,[{'role':'system','content':system},{'role':'user','content':user}],timeout=240)
  return {'answer':str(v.get('answer','')),'citations':v.get('citations',[]),'abstained':bool(v.get('abstained',False)),'answer_elapsed_s':round(time.monotonic()-started,3),'model_response_metrics':{k:raw.get(k) for k in ['prompt_eval_count','eval_count','total_duration']},'error':None}
 except Exception as e:  # noqa: BLE001
  return {'answer':'','citations':[],'abstained':None,'answer_elapsed_s':round(time.monotonic()-started,3),'model_response_metrics':{},'error':type(e).__name__+': '+str(e)[:200]}

def metric(results, questions):
 gold={q['id']:q for q in questions if q.get('mapping_status')=='mapped' and q.get('answerability_in_md')}
 output={}
 for name in ('V1','H1','G1'):
  rows=[r for r in results if r['method']==name and r['question_id'] in gold]
  if not rows:continue
  measurements=collections.defaultdict(list)
  for r in rows:
   ids=[x['chunk_id'] for x in r['retrieved_chunks']];gt=set(gold[r['question_id']]['gold_chunk_ids']);found=[i for i,x in enumerate(ids,1) if x in gt]
   for k in (3,5,10):measurements[f'hit@{k}'].append(float(any(i<=k for i in found)));measurements[f'recall@{k}'].append(len(gt.intersection(ids[:k]))/max(len(gt),1))
   measurements['mrr@10'].append(1/min(found) if found else 0)
   measurements['all_evidence@10'].append(float(gt.issubset(ids[:10])))
  output[name]={'questions':len(rows),**{k:round(statistics.mean(v),5) for k,v in measurements.items()}}
 return output

